import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, r2_score

# 1. File Paths
TRAIN_PATH = '/content/drive/MyDrive/Data/train-test.csv'
VAL_PATH = '/content/drive/MyDrive/Data/validation.csv'
VAL_TEMPLATE_PATH = '/content/drive/MyDrive/Data/validation-predictions-template.csv'
DEC_PATH = '/content/drive/MyDrive/Data/december-chart-inputs.csv'

df_train = pd.read_csv(TRAIN_PATH)
df_val = pd.read_csv(VAL_PATH)

# Identify target dynamically
target_columns = [c for c in df_train.columns if c not in df_val.columns and c != 'load_id']
TARGET_COL = target_columns[0] if target_columns else 'rate'

# 2. UPDATED PREPROCESSING: Dropping cities to prevent flat-lining
def preprocess_features(df, is_training=True):
    data = df.copy()
    data['date'] = pd.to_datetime(data['date'])

    # Granular time features that create the chart fluctuations
    data['day_of_week'] = data['date'].dt.dayofweek
    data['day_of_month'] = data['date'].dt.day
    data['is_weekend'] = data['day_of_week'].isin([5, 6]).astype(int)
    data['time_index'] = (data['date'] - pd.to_datetime('2020-01-01')).dt.days

    data['weight_per_mile'] = data['weight'] / (data['distance'] + 1e-5)

    # ONLY encode equipment. We DROP pickup and delivery to prevent route-overfitting.
    data = pd.get_dummies(data, columns=['equipment'])

    # Drop columns not used for training
    cols_to_drop = ['load_id', 'date', 'pickup', 'delivery']
    if not is_training and TARGET_COL in data.columns:
        cols_to_drop.append(TARGET_COL)

    data = data.drop(columns=[c for c in cols_to_drop if c in data.columns])
    return data

# Process train data
df_processed = preprocess_features(df_train, is_training=True)
X_all = df_processed.drop(columns=[TARGET_COL])
y_all = df_processed[TARGET_COL]
TRAIN_COLUMNS = X_all.columns

# 3. Time-based Split
df_processed = df_processed.sort_values('time_index')
train_size = int(len(X_all) * 0.8)

X_train, X_local_val = X_all.iloc[:train_size], X_all.iloc[train_size:]
y_train, y_local_val = y_all.iloc[:train_size], y_all.iloc[train_size:]

# 4. Train RandomForest
# We use RF because it applies temporal rules much better across generalized distances
print("Training RandomForestRegressor...")
model = RandomForestRegressor(n_estimators=100, min_samples_leaf=4, random_state=42)
model.fit(X_train, y_train)

# Local Validation
val_preds = model.predict(X_local_val)
print(f"Local Validation MAE: ${mean_absolute_error(y_local_val, val_preds):.2f}")

# --- A. Predict for validation.csv ---
df_val_processed = preprocess_features(df_val, is_training=False)
df_val_processed = df_val_processed.reindex(columns=TRAIN_COLUMNS, fill_value=0)

final_val_preds = model.predict(df_val_processed)
final_val_preds = np.clip(final_val_preds, a_min=1.0, a_max=None)

template = pd.read_csv(VAL_TEMPLATE_PATH)
template['predicted_rate'] = final_val_preds
template.to_csv('/content/validation_predictions.csv', index=False)


# --- B. Predict for December Chart (No more flat lines!) ---
df_dec = pd.read_csv(DEC_PATH)
df_dec_processed = preprocess_features(df_dec, is_training=False)
df_dec_processed = df_dec_processed.reindex(columns=TRAIN_COLUMNS, fill_value=0)

dec_preds = model.predict(df_dec_processed)
dec_preds = np.clip(dec_preds, a_min=1.0, a_max=None)

df_dec['predicted_rate'] = dec_preds
df_dec.to_csv(DEC_PATH, index=False)

print("\nPreview of new fluctuating December predictions:")
print(df_dec[['date', 'predicted_rate']].head(10))

